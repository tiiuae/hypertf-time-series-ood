# → canonical, super fast, sanity-check dataset.
# • JapaneseVowels (AUDIO, 270/370, L=29, 9 cls)
# → short-sequence, multi-class; great for receptive-field sensitivity.
# • HandMovementDirection (EEG, 160/74, L=400, 4 cls)
# → moderate-length EEG; good signal/noise stress-test.
# • RacketSports (HAR, 151/152, L=30, 4 cls)
# → common UEA benchmark; very fast, complements BasicMotions.
# • FaceDetection (EEG, 5890/3524, L=62, 2 cls)
# → short but larger-scale EEG; cheap compared to EigenWorms, and widely cited.
